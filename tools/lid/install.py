"""Install a saved model into the extension.

python tools/lid/install.py --data <data-dir> --model NAME

Writes src/content/lid/weights.generated.ts from <data>/lid/models/NAME.bin, and
src/content/lid/parity.fixture.json: 500 bench sentences (Tatoeba, already in
the repo, never chat lines) with the probabilities numpy computes for them.
"""
import argparse
import base64
import json
import pathlib

import numpy as np

import blob

ROOT = pathlib.Path(__file__).resolve().parents[2]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', required=True)
    ap.add_argument('--model', required=True)
    a = ap.parse_args()
    data = pathlib.Path(a.data)
    raw = (data / 'lid' / 'models' / f'{a.model}.bin').read_bytes()
    model = blob.parse(raw)
    (ROOT / 'src/content/lid/weights.generated.ts').write_text(
        '// GENERATED by tools/lid/install.py, do not hand-edit.\n'
        f"// Model {a.model}: {len(raw)} bytes, {len(model['labels'])} languages.\n"
        f"export const LID_WEIGHTS =\n  '{base64.b64encode(raw).decode()}';\n",
        encoding='utf-8', newline='\n')
    feat = data / 'lid' / 'feat'
    p, nz = blob.probs(model, feat, 'bench')
    texts = blob.texts(feat, 'bench')
    pick = [int(k) for k in np.random.default_rng(1).choice(len(texts), 500, replace=False) if nz[k]]
    fixture = [{'text': texts[k]['text'], 'probs': dict(zip(model['labels'], map(float, p[k])))} for k in pick]
    (ROOT / 'src/content/lid/parity.fixture.json').write_text(json.dumps(fixture, ensure_ascii=False), encoding='utf-8')
    print('installed', a.model, len(raw), 'bytes; fixture', len(fixture))


if __name__ == '__main__':
    main()
